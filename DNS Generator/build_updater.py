#!/usr/bin/env python3
"""Build the router auto-updater files from "IP Collector DNS".

Called by generate.py after it writes the collector (or run on its own).
Writes ../ipdns-updater/:

  ipdns-install.rsc  pasted once: creates script securytik-ipdns-update and
                     scheduler securytik-ipdns-daily (re-runnable)
  ipdns-ros7.rsc     the catalog as RouterOS 7 holds it (DNS-static collectors)
  ipdns-ros6.rsc     the catalog as RouterOS 6 holds it (FQDN address-lists)
  ipdns-ros7.size    byte size of ipdns-ros7.rsc (the router checks the
  ipdns-ros6.size    download against it before touching any rule)

Every object the data files create carries a comment starting with "IPDNS:";
the updater removes only those, never the operator's own rules. The "SAMM
skipped" blocks of the collector (DNS servers, DNS redirect NAT, DoT/DoH
blocking, disabled packet marks) are left out: they change how the router
works, not what it collects.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "IP Collector DNS")
OUT = os.path.join(HERE, "..", "ipdns-updater")
TAG = "IPDNS:"
GH = "https://raw.githubusercontent.com/mhdhaidarah/RouterOS-Library/main/ipdns-updater/"
MIRROR = "https://dl.securytik.com/"

FWD = re.compile(r'^add address-list="([^"]+)" comment="([^"]+)" match-subdomain=yes name=(\S+) type=FWD$')
CIDR = re.compile(r'^add address=(\S+) list="([^"]+)"$')
COUNTER = re.compile(r'^add action=passthrough chain=prerouting comment="([^"]+)" (src|dst)-address-list="([^"]+)"$')
GAME = re.compile(r'^/ip firewall mangle add (chain=prerouting action=add-dst-to-address-list .*) comment="([^"]+)" (.*)$')


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def parse(text):
    """Return the collector outside the SAMM-skipped blocks as typed rows."""
    fwd, cidrs, mangle, mangle6 = [], [], [], []
    menu, skipped, extra_time = None, False, None
    for raw in text.splitlines():
        line = raw.strip()
        if line == "# SAMM skipped start":
            skipped = True
            continue
        if line == "# SAMM skipped end":
            skipped = False
            continue
        if skipped or not line or line.startswith("#"):
            continue
        m = GAME.match(line)
        if m:
            mangle.append(f'add {m.group(1)} {m.group(3)} comment={q(TAG + " " + m.group(2))}')
            continue
        if line.startswith("/"):
            if line.startswith("/ip dns set "):
                m = re.search(r"address-list-extra-time=(\S+)", line)
                extra_time = m.group(1) if m else None
                menu = None
            elif line in ("/ip dns static", "/ip firewall address-list", "/ip firewall mangle", "/ipv6 firewall mangle"):
                menu = line
            else:
                raise SystemExit(f"build_updater: unknown menu line: {line}")
            continue
        if line == 'remove [find where comment~"Traffic"]':
            continue  # the updater removes its own (IPDNS:) rules instead
        if menu == "/ip dns static" and (m := FWD.match(line)):
            fwd.append((m.group(1), m.group(2), m.group(3)))
        elif menu == "/ip firewall address-list" and (m := CIDR.match(line)):
            cidrs.append((m.group(2), m.group(1)))
        elif menu in ("/ip firewall mangle", "/ipv6 firewall mangle") and (m := COUNTER.match(line)):
            row = f'add action=passthrough chain=prerouting comment={q(TAG + " " + m.group(1))} {m.group(2)}-address-list={q(m.group(3))}'
            (mangle if menu == "/ip firewall mangle" else mangle6).append(row)
        else:
            raise SystemExit(f"build_updater: line not understood under {menu}: {line}")
    return fwd, cidrs, mangle, mangle6, extra_time


def header(ver):
    return (f"# IP Collector DNS for RouterOS {ver}: AUTO-GENERATED by \"DNS Generator/build_updater.py\".\n"
            f"# Imported by the router script securytik-ipdns-update (see README). Every entry is tagged \"{TAG}\";\n"
            f"# the updater removes those before importing this file. Not for pasting by hand.\n")


def build_ros7(fwd, cidrs, mangle, mangle6, extra_time):
    out = [header(7)]
    if extra_time:
        out.append(f"/ip dns set address-list-extra-time={extra_time}")
    out.append("/ip dns static")
    out += [f"add address-list={q(lst)} comment={q(TAG + ' ' + c)} match-subdomain=yes name={n} type=FWD"
            for lst, c, n in fwd]
    out.append("/ip firewall address-list")
    out += [f"add address={a} list={q(lst)} comment={q(TAG + ' ' + lst)}" for lst, a in _uniq(cidrs)]
    out.append("/ip firewall mangle")
    out += mangle
    out.append("/ipv6 firewall mangle")
    out += mangle6
    out.append(':global ipdnsLoaded "ros7"')
    return "\n".join(out) + "\n"


def build_ros6(fwd, cidrs, mangle, mangle6, extra_time):
    # RouterOS 6 has no DNS-static address-list=: each collector domain becomes an address-list entry holding the
    # name (RouterOS 6 resolves it and keeps the addresses in the list). Exact names only, so a bare domain also gets
    # its "www." form: the same rule as SAMM's delivery_render.for_ros6. IPv6 counters are left out: RouterOS 6
    # FQDN entries fill IPv4 lists only.
    rows = []
    for lst, _c, n in fwd:
        rows.append((lst, n))
        if n.count(".") == 1:
            rows.append((lst, "www." + n))
    rows += cidrs
    out = [header(6), "/ip firewall address-list"]
    out += [f"add address={a} list={q(lst)} comment={q(TAG + ' ' + lst)}" for lst, a in _uniq(rows)]
    out.append("/ip firewall mangle")
    out += mangle
    out.append(':global ipdnsLoaded "ros6"')
    return "\n".join(out) + "\n"


def _uniq(pairs):
    seen, out = set(), []
    for p in pairs:
        if p not in seen:
            seen.add(p)
            out.append(p)
    return out


UPDATE_SCRIPT = r'''# securytik-ipdns-update: refresh the IP Collector DNS catalog (RouterOS 6 and 7).
# Downloads first; touches no rule unless the file arrived whole. Removes only entries tagged IPDNS:
:local bases {"__GH__";"__MIRROR__"}
:local v "ros7"
:if ([:pick [/system resource get version] 0 1] = "6") do={ :set v "ros6" }
:local f ("ipdns-" . $v . ".rsc")
:local ok false
:foreach b in=$bases do={
  :if (!$ok) do={
    :do {
      :local r [/tool fetch url=($b . "ipdns-" . $v . ".size") output=user as-value]
      :local want [:tonum ($r->"data")]
      :if ([:typeof $want] = "num" && $want > 10000) do={
        :do { /file remove [find name=$f] } on-error={}
        /tool fetch url=($b . $f) dst-path=$f
        :delay 3s
        :local got [:tonum [/file get [find name=$f] size]]
        :if ($got = $want) do={ :set ok true } else={ :log warning ("IPDNS: size mismatch from " . $b . " (" . $got . "/" . $want . ")") }
      } else={ :log warning ("IPDNS: bad size file from " . $b) }
    } on-error={ :log warning ("IPDNS: download failed from " . $b) }
  }
}
:if (!$ok) do={
  :do { /file remove [find name=$f] } on-error={}
  :log error "IPDNS: no valid catalog downloaded, current rules kept"
  :error "IPDNS: download failed, current rules kept"
}
/ip firewall mangle remove [find where comment~"^IPDNS:"]
:do { [[:parse "/ipv6 firewall mangle remove [find where comment~\"^IPDNS:\"]"]] } on-error={}
/ip firewall address-list remove [find where comment~"^IPDNS:"]
/ip dns static remove [find where comment~"^IPDNS:"]
:global ipdnsLoaded ""
:do { /import file-name=$f } on-error={ :log error "IPDNS: import stopped with an error" }
/file remove [find name=$f]
:if ($ipdnsLoaded = $v) do={ :log info ("IPDNS: catalog updated (" . $v . ")") } else={ :log error "IPDNS: import incomplete" }
'''


def build_install():
    src = UPDATE_SCRIPT.replace("__GH__", GH).replace("__MIRROR__", MIRROR)
    pol = "read,write,policy,test"
    return f"""# IP Collector DNS auto-updater installer (RouterOS 6 and 7): AUTO-GENERATED by "DNS Generator/build_updater.py".
# Creates script securytik-ipdns-update and scheduler securytik-ipdns-daily (once a day, 04:17).
# Safe to run again: it replaces both.
/system scheduler remove [find name="securytik-ipdns-daily"]
/system script remove [find name="securytik-ipdns-update"]
/system script add name=securytik-ipdns-update policy={pol} comment="IPDNS: IP Collector DNS updater (github.com/mhdhaidarah/RouterOS-Library)" source={{
{src}}}
/system scheduler add name=securytik-ipdns-daily interval=1d start-time=04:17:00 policy={pol} comment="IPDNS: daily IP Collector DNS update" on-event="/system script run securytik-ipdns-update"
:do {{ /file remove [find name="ipdns-install.rsc"] }} on-error={{}}
:put "IP Collector DNS updater installed. Run it now: /system script run securytik-ipdns-update"
"""


def main():
    with open(SRC, encoding="utf-8") as f:
        parsed = parse(f.read())
    os.makedirs(OUT, exist_ok=True)
    files = {
        "ipdns-ros7.rsc": build_ros7(*parsed),
        "ipdns-ros6.rsc": build_ros6(*parsed),
        "ipdns-install.rsc": build_install(),
    }
    for name, text in files.items():
        data = text.encode("utf-8")
        with open(os.path.join(OUT, name), "wb") as f:
            f.write(data)
        if name.startswith("ipdns-ros"):
            with open(os.path.join(OUT, name.replace(".rsc", ".size")), "w") as f:
                f.write(str(len(data)))
    fwd, cidrs, mangle, mangle6, _ = parsed
    print(f"Wrote ipdns-updater/: {len(fwd)} DNS collectors, {len(cidrs)} ranges, "
          f"{len(mangle)} mangle, {len(mangle6)} ipv6 mangle")


if __name__ == "__main__":
    main()
